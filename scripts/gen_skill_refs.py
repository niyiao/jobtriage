#!/usr/bin/env python3
"""Generate the skills' reference files from the code they describe.

Plan 05 step 2: `cli.md` from the argparse tree and `schema.md` from a
freshly migrated database. The point is not saving typing — it is that a
skill cannot drift from the CLI. The committed files are compared
against a fresh render by tests/test_skill_refs.py, so adding a flag, a
command or a column without regenerating fails the suite instead of
quietly leaving an agent with an outdated map.

This is a repository script, not a CLI subcommand: users install the
package; contributors run the generator. Stdlib only, apart from
importing jobtriage itself (the argparse tree and migration runner are
the sources of truth, and duplicating them here would defeat the test).

Usage:

    uv run python scripts/gen_skill_refs.py            # write the committed files
    uv run python scripts/gen_skill_refs.py --check    # fail if they are stale
    uv run python scripts/gen_skill_refs.py OUT_DIR    # render somewhere else

The schema's per-column meanings come from `jobtriage.cli.db`'s
`_COMMENTS` — the same annotations `jobtriage db schema` prints — so
the agent-facing Markdown and the terminal command cannot disagree. A
new column with no annotation is a generation error, deliberately: an
undocumented column is exactly what this file exists to prevent.
"""

import argparse
import sqlite3
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / 'src' / 'jobtriage' / 'assets' / 'skills'

# If the package is not installed in the interpreter running this file,
# a checkout still works: the repo's src/ is the next thing to import.
sys.path.insert(0, str(ROOT / 'src'))

CLI_PATH = Path('jobtriage/references/cli.md')
SCHEMA_PATH = Path('jobtriage-db/references/schema.md')

GENERATED = '<!-- Generated by scripts/gen_skill_refs.py. Do not edit: run the generator. -->'

# One paragraph per table, explaining what a row is *for*. The columns
# carry their own meanings in cli/db.py; this is the table-level why.
TABLE_NOTES = {
	'jobs': 'One row per posting the pipeline has seen. `first_seen`, `title`, '
	'`published` and `locations` are the first sighting; a later scrape only '
	'touches `last_seen` and the pointer data (`url`, `salary`, `source`). '
	'`status` and `notes` belong to the person triaging and are never written '
	'by a scrape.',
	'status_history': 'One row per status change, with who made it. This is what '
	'`jobtriage show` prints and what undo reads; the current status also lives on '
	'`jobs.status`.',
	'attachments': 'One row per file recorded against a job — plan 05 cover '
	'letters and the like. `path` is workspace-relative when the file lives in '
	'or under the op folder, absolute otherwise.',
	'source_runs': 'One row per board attempt, success or failure. The health '
	'surfaces (`jobtriage sources`, the end of a scrape) summarise the last ten; a '
	'row is history about a board name, not a foreign key to one.',
}

EXIT_CODES = """\
## Exit codes and errors

- `0` — success (and, for `filter test`, "the title is kept").
- `1` — a runtime failure: a missing job, a broken config or board, a
  database that cannot be read or is from a newer build. `filter test`
  also uses 1 for "the title is dropped".
- `2` — usage: argparse's own errors (a missing argument, an unknown
  command, a bad number), an unknown status slug, an unknown board name.

Every failure is one line beginning `error:` on stderr; stdout stays
clean so a `--json` document can be piped. A command whose table has a
`--json` flag (or `export --format json`) is the machine-readable
surface; the write commands print a short confirmation instead.
"""


def render() -> dict[str, str]:
	"""Every generated file's content, keyed by its path under the skills root."""
	return {
		CLI_PATH.as_posix(): render_cli(),
		SCHEMA_PATH.as_posix(): render_schema(),
	}


# -- cli.md ---------------------------------------------------------------


def render_cli() -> str:
	"""The whole command surface, walked from build_parser()."""
	from jobtriage.cli.main import build_parser

	parser = build_parser()
	header = '\n'.join(
		[
			'# jobtriage CLI reference',
			'',
			GENERATED,
			'',
			'Every command, argument and flag, read from the parser itself. Run',
			'`jobtriage COMMAND --help` for the same text in a terminal.',
			'',
			'Global options come before the command:',
			'',
			'    jobtriage --workspace PATH list --json',
			'',
			'\n'.join(_options_section(parser)),
		]
	)
	parts = [header]
	for child, help_text in _children(parser):
		parts.append('\n'.join(_command_section(child, help_text)))
	parts.append(EXIT_CODES.rstrip())
	return '\n\n'.join(part for part in parts if part) + '\n'


def _children(parser: argparse.ArgumentParser):
	"""(subparser, one-line help) for each direct subcommand, in parser order."""
	for action in parser._actions:
		if not isinstance(action, argparse._SubParsersAction):
			continue
		helps = {choice.dest: choice.help or '' for choice in action._choices_actions}
		for name, child in action.choices.items():
			yield child, helps.get(name, '')


def _command_section(parser: argparse.ArgumentParser, help_text: str) -> list[str]:
	"""One command: heading, help, its arguments, then its subcommands."""
	lines = [f'## `{parser.prog}`', '']
	if help_text:
		lines.extend([_cell(help_text), ''])

	options = _options_section(parser)
	if options:
		lines.extend(options)

	children = list(_children(parser))
	if children:
		if options:
			lines.append('')
		lines.extend(['**Subcommands**', '', '| Command | What it does |', '| --- | --- |'])
		for child, child_help in children:
			lines.append(f'| `{child.prog}` | {_cell(child_help)} |')
	while lines and lines[-1] == '':
		lines.pop()
	return lines


def _options_section(parser: argparse.ArgumentParser) -> list[str]:
	"""The parser's arguments and flags as one table, in declaration order."""
	rows = []
	for action in parser._actions:
		if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
			continue
		rows.append(_option_row(action))
	if not rows:
		return []
	lines = ['| Argument / flag | Default | Description |', '| --- | --- | --- |']
	lines.extend(rows)
	return lines


def _option_row(action: argparse.Action) -> str:
	"""`| `--flag VALUE` | `default` | help |`, with dest and choices when they matter."""
	name = _action_name(action)
	default = _default_text(action)
	description = _cell(action.help or '') or '—'

	details = []
	dest = getattr(action, 'dest', '')
	if action.option_strings:
		long_options = [option for option in action.option_strings if option.startswith('--')]
		expected_dest = (long_options[0] if long_options else action.option_strings[0]).lstrip('-')
		expected_dest = expected_dest.replace('-', '_')
		if dest and dest != expected_dest:
			details.append(f'dest `{dest}`')
	if action.choices:
		choices = ', '.join(f'`{choice}`' for choice in action.choices)
		details.append(f'one of {choices}')
	if details:
		description = f'{description}{" — " if description else ""}{"; ".join(details)}'
	return f'| {name} | {default} | {description} |'


def _action_name(action: argparse.Action) -> str:
	"""The invocation spelling: `-s, --source BOARD`, `ID`, `[PATH]`."""
	if action.option_strings:
		text = ', '.join(f'`{option}`' for option in action.option_strings)
		suffix = _value_suffix(action)
		return f'{text} {suffix}' if suffix else text
	return _value_suffix(action)


def _value_name(action: argparse.Action) -> str:
	"""The metavar or a sensible one, without nargs decoration."""
	metavar = action.metavar
	if isinstance(metavar, tuple):
		metavar = ' '.join(str(part) for part in metavar)
	if metavar:
		return str(metavar)
	if action.option_strings:
		return action.dest.upper()
	return action.dest


def _value_suffix(action: argparse.Action) -> str:
	"""nargs decoration around the metavar: `N`, `[N]`, `TITLE [...]`."""
	value = _value_name(action)
	if action.nargs == 0:
		return ''  # an action that takes no value (--version, a custom flag)
	if isinstance(
		action,
		(argparse._StoreTrueAction, argparse._StoreFalseAction, argparse._VersionAction),
	):
		return ''
	if action.nargs == '?':
		return f'`[{value}]`'
	if action.nargs == '+':
		return f'`{value} [...]`'
	if action.nargs == '*':
		return f'`[{value} ...]`'
	if action.nargs == argparse.REMAINDER:
		return f'`[{value} ...]`'
	if isinstance(action.nargs, int) and action.nargs > 1:
		return ' '.join(f'`{value}`' for _ in range(action.nargs))
	return f'`{value}`'


def _default_text(action: argparse.Action) -> str:
	"""The default where it says something useful; an em dash otherwise.

	`False` is the store_true default and `None` is argparse's "not
	given": printing either on every boolean or optional flag would bury
	the defaults that matter (`50`, `csv`, `published`).
	"""
	default = action.default
	if default is None or default is False or default is argparse.SUPPRESS:
		return '—'
	if default is True:
		return '`true`'
	if isinstance(default, str):
		return f'`{default}`'
	if isinstance(default, (list, tuple)):
		inner = ', '.join(f'`{value}`' for value in default)
		return f'[{inner}]'
	return f'`{default}`'


def _cell(text: str) -> str:
	"""Prose safe inside a Markdown table cell."""
	text = ' '.join(str(text).split())
	return text.replace('|', '\\|').replace('<', '&lt;').replace('>', '&gt;')


# -- schema.md -------------------------------------------------------------


def render_schema() -> str:
	"""Every table and column, from a database the migrations just built."""
	from jobtriage import db
	from jobtriage.cli.db import _COMMENTS as comments

	with tempfile.TemporaryDirectory() as folder:
		tmp = Path(folder)
		path = tmp / 'schema.db'
		version = db.migrate(path, tmp / 'backups')
		conn = db.connect(path)
		try:
			tables = [
				row[0]
				for row in conn.execute(
					"SELECT name FROM sqlite_master WHERE type = 'table'"
					" AND name NOT LIKE 'sqlite_%' ORDER BY rowid"
				)
			]
			sections = [_table_section(conn, table, comments) for table in tables]
		finally:
			conn.close()

	lines = [
		'# jobtriage database schema',
		'',
		GENERATED,
		'',
		f'Schema version **{version}**, rendered from a fresh database.',
		'',
		'Read it with `jobtriage db shell "SELECT ..."` or any read-only SQLite',
		'client. Changes go through `jobtriage status`, `jobtriage note` and',
		'`jobtriage attach`; writing the database with SQL bypasses status history,',
		'the actor and the unique key that keeps a re-scrape from duplicating a job.',
		'',
	]
	for section in sections:
		lines.extend(section)
		lines.append('')
	return '\n'.join(lines).rstrip() + '\n'


def _table_section(conn: sqlite3.Connection, table: str, comments: dict) -> list[str]:
	"""One table: what it is, its columns and their meanings, its indexes."""
	columns = conn.execute(f'PRAGMA table_info("{table}")').fetchall()
	foreign = {
		row['from']: f'{row["table"]}.{row["to"] or "id"}'
		+ (f' ON DELETE {row["on_delete"]}' if row['on_delete'] else '')
		for row in conn.execute(f'PRAGMA foreign_key_list("{table}")')
	}

	lines = [f'## {table}', '']
	if table in TABLE_NOTES:
		lines.extend([TABLE_NOTES[table], ''])

	lines.extend(['| Column | Type | Constraints | Meaning |', '| --- | --- | --- | --- |'])
	for column in columns:
		rules = []
		if column['pk']:
			rules.append('PRIMARY KEY')
		if column['notnull']:
			rules.append('NOT NULL')
		if column['dflt_value'] is not None:
			rules.append(f'DEFAULT {column["dflt_value"]}')
		if column['name'] in foreign:
			rules.append(f'→ {foreign[column["name"]]}')
		meaning = comments.get(table, {}).get(column['name'])
		if meaning is None:
			raise ValueError(
				f'no meaning recorded for {table}.{column["name"]}: '
				'add it to _COMMENTS in src/jobtriage/cli/db.py'
			)
		lines.append(
			f'| `{column["name"]}` | {column["type"] or "—"} | '
			f'{_cell(" ".join(rules)) or "—"} | {_cell(meaning)} |'
		)

	indexes, unique = _indexes(conn, table)
	if indexes or unique:
		lines.append('')
	if indexes:
		lines.append('Indexes: ' + ', '.join(f'`{index}`' for index in indexes))
	if unique:
		spellings = '; '.join(f'`{columns}`' for columns in unique)
		lines.append(f'Unique: {spellings}')
	return lines


def _indexes(conn: sqlite3.Connection, table: str) -> tuple[list[str], list[str]]:
	"""The named indexes and the unique constraints, sorted for stable output."""
	indexes, unique = [], []
	for index in conn.execute(f'PRAGMA index_list("{table}")'):
		columns = ', '.join(
			column['name'] or '' for column in conn.execute(f'PRAGMA index_info("{index["name"]}")')
		)
		if index['origin'] == 'u':
			unique.append(columns)
		elif index['origin'] == 'c':
			indexes.append(f'{index["name"]} ({columns})')
	return sorted(indexes), sorted(unique)


# -- running it ------------------------------------------------------------


def write(root: Path) -> list[Path]:
	"""Render and write every file whose content changed; return the paths."""
	written = []
	for relative, text in render().items():
		path = root / relative
		if path.is_file() and path.read_text(encoding='utf-8') == text:
			continue
		path.parent.mkdir(parents=True, exist_ok=True)
		path.write_text(text, encoding='utf-8')
		written.append(path)
	return written


def stale(root: Path) -> list[Path]:
	"""The generated files that are missing or differ from a fresh render."""
	outdated = []
	for relative, text in render().items():
		path = root / relative
		if not path.is_file() or path.read_text(encoding='utf-8') != text:
			outdated.append(path)
	return outdated


def main(argv: list[str] | None = None) -> int:
	parser = argparse.ArgumentParser(description='Generate the skills reference files.')
	parser.add_argument(
		'output_dir',
		nargs='?',
		type=Path,
		default=DEFAULT_OUTPUT,
		help='skills root to write under (default: the package assets)',
	)
	parser.add_argument(
		'--check',
		action='store_true',
		help='write nothing; exit 1 when the committed files are stale',
	)
	args = parser.parse_args(argv)

	if args.check:
		outdated = stale(args.output_dir)
		if outdated:
			for path in outdated:
				print(f'stale: {path}', file=sys.stderr)
			print('run `uv run python scripts/gen_skill_refs.py`', file=sys.stderr)
			return 1
		print('skill references are current')
		return 0

	written = write(args.output_dir)
	for path in written:
		print(f'wrote {path}')
	if not written:
		print('skill references are current')
	return 0


if __name__ == '__main__':
	raise SystemExit(main())
